  ## --- Lifecycle Callbacks ---

  @impl true
  def mount(_params, _session, socket) do
    # Get project title from settings

    socket =
      socket
      |> assign(:page_title, gettext("Email Templates"))
      |> assign(:page_subtitle, gettext("Manage and organize your email templates"))
      |> assign(:templates, [])
      |> assign(:template_sources, TemplateSources.empty())
      |> assign(:template_sources_loaded, false)
      |> assign(:total_count, 0)
      |> assign(:stats, %{})
      |> assign(:loading, true)
      |> assign(:show_clone_modal, false)
      |> assign(:clone_template, nil)
      |> assign(:clone_form, %{name: "", display_name: "", errors: %{}})
      |> assign(:confirmation_modal, %{show: false})
      |> assign(:display_locale, Settings.get_content_language() || "en")
      |> assign(:sort_by, :inserted_at)
      |> assign(:sort_dir, :desc)
      |> assign_filter_defaults()
      |> assign_pagination_defaults()

    {:ok, socket}
  end

  @impl true
  def handle_params(params, _url, socket) do
    socket =
      socket
      |> apply_params(params)
      |> load_template_sources()
      |> load_templates()
      |> load_stats()

    {:noreply, socket}
  end

  ## --- Event Handlers ---

  @impl true
  def handle_event("filter", params, socket) do
    # Handle both search and filter parameters
    combined_params = %{}

    # Extract search parameters
    combined_params =
      case Map.get(params, "search") do
        %{"query" => query} ->
          Map.put(combined_params, "search", String.trim(Utils.string_param(query)))

        _ ->
          combined_params
      end

    # Extract filter parameters
    combined_params =
      case Map.get(params, "filter") do
        # Only flat string values: a crafted event can nest a map or list here,
        # which URI.encode_query/1 raises on when the URL is built below.
        filter_params when is_map(filter_params) ->
          Map.merge(combined_params, Map.filter(filter_params, fn {_k, v} -> is_binary(v) end))

        _ ->
          combined_params
      end

    # Reset to first page when filtering
    combined_params = Map.put(combined_params, "page", "1")

    # Build new URL parameters
    new_params = build_url_params(socket.assigns, combined_params)

    {:noreply,
     socket
     |> push_patch(to: Routes.path("/admin/emails/templates?#{new_params}"))}
  end

  @impl true
  def handle_event("clear_filters", _params, socket) do
    {:noreply,
     socket
     |> push_patch(to: Routes.path("/admin/emails/templates"))}
  end

  @impl true
  def handle_event("clear_search", _params, socket) do
    # Clear only the search term (the × inside the search box); keep the other
    # filters and reset to page 1.
    new_params = build_url_params(socket.assigns, %{"search" => "", "page" => "1"})

    {:noreply, push_patch(socket, to: Routes.path("/admin/emails/templates?#{new_params}"))}
  end

  @impl true
  def handle_event("set_filter", %{"field" => field, "value" => value}, socket)
      when is_binary(field) and is_binary(value) do
    # Dropdown filter selection (category/status/is_system): set the chosen
    # filter, reset to page 1, and patch. Empty value clears that filter.
    new_params = build_url_params(socket.assigns, %{field => value, "page" => "1"})

    {:noreply, push_patch(socket, to: Routes.path("/admin/emails/templates?#{new_params}"))}
  end

  # A crafted field or value that is not a string would reach
  # URI.encode_query/1 and raise; keep the current filters instead.
  @impl true
  def handle_event("set_filter", _params, socket), do: {:noreply, socket}

  @impl true
  def handle_event("toggle_sort", %{"by" => by}, socket) do
    # Clicking a sortable column header: validate the field, then toggle the
    # direction if it's already the active sort, otherwise switch to that field
    # ascending. Resets to page 1 and patches.
    field = validate_sort_by(by)

    sort_dir =
      if field == socket.assigns.sort_by do
        if socket.assigns.sort_dir == :asc, do: :desc, else: :asc
      else
        :asc
      end

    new_params =
      build_url_params(socket.assigns, %{
        "sort_by" => to_string(field),
        "sort_dir" => to_string(sort_dir),
        "page" => "1"
      })

    {:noreply, push_patch(socket, to: Routes.path("/admin/emails/templates?#{new_params}"))}
  end

  @impl true
  def handle_event("refresh", _params, socket) do
    {:noreply,
     socket
     |> assign(:loading, true)
     |> load_template_sources(force: true)
     |> load_templates()
     |> load_stats()}
  end

  @impl true
  def handle_event("show_clone_modal", %{"uuid" => template_uuid}, socket) do
    case Templates.get_template(template_uuid) do
