  # Turns the first changeset error into a short, translated "field: reason"
  # string a flash can show (e.g. "name: is reserved for a system email")
  # instead of a bare "something went wrong" that hides why. Shared by
  # archive/activate/clone failures. Ecto's traverse_errors/2 already
  # interpolates any %{count}/%{min}/etc. from validation opts into msg.
  defp changeset_error_reason(changeset) do
    changeset
    |> Ecto.Changeset.traverse_errors(fn {msg, opts} ->
      # Only interpolate placeholders actually present in msg — opts also
      # carries non-string metadata (e.g. a cast error's `type: {:array, _}`)
      # that to_string/1 would crash on.
      Regex.replace(~r/%{(\w+)}/, msg, &interpolate_error_opt(&1, &2, opts))
    end)
    |> Enum.flat_map(fn {field, msgs} -> Enum.map(msgs, &"#{field}: #{&1}") end)
    |> List.first()
  end

  defp interpolate_error_opt(placeholder, key, opts) do
    case Enum.find(opts, fn {k, _} -> Atom.to_string(k) == key end) do
      {_, value} -> to_string(value)
      nil -> placeholder
    end
  end

  defp archive_failure_message(changeset) do
    case changeset_error_reason(changeset) do
      nil -> gettext("Failed to archive template")
      reason -> gettext("Failed to archive template: %{reason}", reason: reason)
    end
  end

  defp activate_failure_message(changeset) do
    case changeset_error_reason(changeset) do
      nil -> gettext("Failed to activate template")
      reason -> gettext("Failed to activate template: %{reason}", reason: reason)
    end
  end

  # Who is acting, from the session — recorded as the editor or author.
  defp current_user_uuid(socket), do: Scope.user_uuid(socket.assigns[:phoenix_kit_current_scope])

  # Shared by the "archive_template" event (uuid lookup — from confirm_action
  # after a system-row confirmation, or the plain uuid-only client event) and
  # request_archive's non-system branch (which already has `template` loaded
  # and would otherwise fetch it a second time).
  defp do_archive(socket, template) do
    case Templates.archive_template(template, current_user_uuid(socket)) do
      {:ok, archived_template} ->
        {:noreply,
         socket
         |> put_flash(:info, archive_success_message(archived_template))
         |> load_templates()
         |> load_stats()}

      {:error, changeset} ->
        {:noreply,
         socket
         |> put_flash(:error, archive_failure_message(changeset))}
    end
  end

  defp do_activate(socket, template) do
    case Templates.activate_template(template, current_user_uuid(socket)) do
      {:ok, activated_template} ->
        {:noreply,
         socket
         |> put_flash(:info, activate_success_message(activated_template))
         |> load_templates()
         |> load_stats()}

      {:error, changeset} ->
        {:noreply,
         socket
         |> put_flash(:error, activate_failure_message(changeset))}
    end
  end

  # Apply default filter values
  defp assign_filter_defaults(socket) do
    filters = %{
      search: "",
      category: "",
      status: "",
      is_system: ""
    }

    assign(socket, :filters, filters)
  end

  # Apply default pagination values
  defp assign_pagination_defaults(socket) do
    socket
    |> assign(:page, 1)
    |> assign(:per_page, @default_per_page)
    |> assign(:total_pages, 0)
  end

  # Apply URL parameters to socket assigns
  defp apply_params(socket, params) do
    filters = %{
      search: params["search"] || "",
      category: params["category"] || "",
      status: params["status"] || "",
      is_system: params["is_system"] || ""
    }

    page = Utils.parse_page(params["page"])

    per_page =
      Utils.parse_int(params["per_page"], @default_per_page,
        min: 1,
        max: @max_per_page,
        above_max: :clamp
      )

    sort_by = validate_sort_by(params["sort_by"])
    sort_dir = validate_sort_dir(params["sort_dir"])

    socket
    |> assign(:filters, filters)
    |> assign(:page, page)
    |> assign(:per_page, per_page)
    |> assign(:sort_by, sort_by)
    |> assign(:sort_dir, sort_dir)
  end

  # Load templates based on current filters and pagination
  defp load_templates(socket) do
    %{filters: filters, page: page, per_page: per_page} = socket.assigns

    # Get total count for pagination (the count query drops limit/offset and
    # ordering)
    total_count =
      Templates.count_templates(Map.drop(build_query_filters(filters, 1, 1), [:limit, :offset]))

    # Floor of 1 so an empty list still has a page to sit on. A ?page past the
    # end (a stale bookmark, a hand-edited URL) lands on the last page instead
    # of an empty one with no pagination left to get back — same as Blocklist.
    total_pages = max(ceil(total_count / per_page), 1)
    page = Utils.clamp_page(page, total_pages)

    query_filters =
      build_query_filters(filters, page, per_page)
      |> Map.put(:order_by, socket.assigns.sort_by)
      |> Map.put(:order_direction, socket.assigns.sort_dir)

    templates = Templates.list_templates(query_filters)

    socket
    |> assign(:page, page)
    |> assign(:templates, templates)
    |> assign(:total_count, total_count)
    |> assign(:total_pages, total_pages)
    |> assign(:loading, false)
  end

  # The file overrides and defaults a row can hide do not depend on the filters
  # or the page, and reading them walks the override directories: read once
  # per mount, again on refresh.
  defp load_template_sources(socket, opts \\ []) do
    if socket.assigns[:template_sources_loaded] && !Keyword.get(opts, :force, false) do
      socket
    else
      socket
      |> assign(:template_sources, TemplateSources.load())
      |> assign(:template_sources_loaded, true)
    end
  end

  # Load template statistics
  defp load_stats(socket) do
    stats = Templates.get_template_stats()
    assign(socket, :stats, stats)
  end

  # Build query filters from form filters
  defp build_query_filters(filters, page, per_page) do
    query_filters = %{
      limit: per_page,
      offset: (page - 1) * per_page,
      order_by: :inserted_at,
      order_direction: :desc
    }

    # Add non-empty filters
    filters
    |> Enum.reduce(query_filters, fn
      {:search, search}, acc when search != "" ->
        Map.put(acc, :search, search)

      {:category, category}, acc when category != "" ->
        Map.put(acc, :category, category)

      {:status, status}, acc when status != "" ->
        Map.put(acc, :status, status)

      {:is_system, is_system}, acc when is_system != "" ->
        Map.put(acc, :is_system, is_system == "true")

      _, acc ->
        acc
    end)
  end

  # Build URL parameters from current state
  defp build_url_params(assigns, additional_params) do
    base_params = %{
      "search" => assigns.filters.search,
      "category" => assigns.filters.category,
      "status" => assigns.filters.status,
      "is_system" => assigns.filters.is_system,
      "sort_by" => to_string(assigns.sort_by),
      "sort_dir" => to_string(assigns.sort_dir),
      "page" => assigns.page,
      "per_page" => assigns.per_page
    }

    Map.merge(base_params, additional_params)
    |> Enum.reject(fn {_key, value} -> value == "" or is_nil(value) end)
    |> Map.new()
    |> URI.encode_query()
  end

  # Whitelist of fields that may be passed to Templates.list_templates/1
  # :order_by. Anything outside this set falls back to the default inserted_at.
  # These are the only DB columns the context's apply_ordering/2 supports.
  # Only Name (the "Template" column) and Usage get clickable sort headers.
  # Category and Status are intentionally not sortable because the context's
  # apply_ordering/2 does not order by them.
  @sort_fields [:name, :usage_count, :last_used_at, :inserted_at]

  defp validate_sort_by(value) when is_atom(value) do
    if value in @sort_fields, do: value, else: :inserted_at
  end

  defp validate_sort_by(value) when is_binary(value) do
    case Enum.find(@sort_fields, fn field -> Atom.to_string(field) == value end) do
      nil -> :inserted_at
      field -> field
    end
  end

  defp validate_sort_by(_), do: :inserted_at

  defp validate_sort_dir(:asc), do: :asc
  defp validate_sort_dir(:desc), do: :desc
  defp validate_sort_dir("asc"), do: :asc
  defp validate_sort_dir("desc"), do: :desc
  defp validate_sort_dir(_), do: :desc

  # Surfaces the changeset's actual error (e.g. the reserved-name rejection)
  # instead of a bare "something went wrong" — the pre-submit uniqueness
  # check in validate_clone_form/1 doesn't catch a reserved name with no
  # existing row, so this is often the only place that reason is seen.
  defp clone_failure_message(changeset) do
    case changeset_error_reason(changeset) do
      nil -> gettext("Failed to clone template")
      reason -> gettext("Failed to clone template: %{reason}", reason: reason)
    end
  end

  # The clone form's name and display name, as strings. A crafted event can
  # send a non-map form or non-string fields; they read as blank, so validation
  # reports them and the form re-renders with strings, not raw values (which
  # the template cannot render).
  defp clone_params(%{"clone" => clone}) when is_map(clone) do
    %{
      "name" => Utils.string_param(clone["name"]),
      "display_name" => Utils.string_param(clone["display_name"])
    }
  end

  defp clone_params(_params), do: %{"name" => "", "display_name" => ""}

  # Validate clone form
  defp validate_clone_form(params) do
    errors = %{}

    # Validate name
    errors =
      case String.trim(params["name"]) do
        "" ->
          Map.put(errors, :name, "Name is required")

        name ->
          cond do
            not Regex.match?(~r/^[a-z][a-z0-9_]*$/, name) ->
              Map.put(
                errors,
                :name,
                "Must start with a letter and contain only lowercase letters, numbers, and underscores"
              )

            # A clone is always non-system, so the changeset would reject
            # this on submit anyway — flag it inline while typing instead.
            name in Template.reserved_names() ->
              Map.put(errors, :name, "Name is reserved for a system email")

            Templates.get_template_by_name(name) != nil ->
              Map.put(errors, :name, "Name already exists")

            true ->
              errors
          end
      end

    # Validate display_name
    errors =
      case String.trim(params["display_name"]) do
        "" ->
          Map.put(errors, :display_name, "Display name is required")

        _ ->
          errors
      end

    errors
  end
end
